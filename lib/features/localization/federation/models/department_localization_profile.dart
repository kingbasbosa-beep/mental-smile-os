class DepartmentLocalizationProfile {
  const DepartmentLocalizationProfile({
    required this.departmentId,
    required this.nameAr,
    required this.nameEn,
    required this.shortLabelAr,
    required this.shortLabelEn,
    required this.easyReadingAr,
    required this.easyReadingEn,
    required this.screenReaderAr,
    required this.screenReaderEn,
  });

  final String departmentId;
  final String nameAr;
  final String nameEn;
  final String shortLabelAr;
  final String shortLabelEn;
  final String easyReadingAr;
  final String easyReadingEn;
  final String screenReaderAr;
  final String screenReaderEn;
}
